#!/usr/bin/env python3
"""Generate runtime version expectations from the checked-in dependency pins."""

import argparse
import importlib.util
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    pins = dict(re.findall(r'^([A-Z_]+)="([^"\n]+)"$',
                          (ROOT / "Config/Dependencies.sh").read_text(), re.M))
    names = {"ytDLP": "YTDLP_VERSION", "ejs": "YTDLP_EJS_VERSION",
             "quickJS": "QUICKJS_VERSION", "python": "CPYTHON_VERSION",
             "certifi": "CERTIFI_VERSION", "lame": "LAME_VERSION", "ffmpeg": "FFMPEG_VERSION"}
    for pin in names.values():
        if not re.fullmatch(r"[0-9]+(?:\.[0-9]+)*", pins[pin]):
            raise ValueError(f"Invalid runtime version: {pin}")
    swift = "// Generated by Scripts/sync-dependency-versions.py.\n"
    swift += "enum DependencyVersions {\n"
    profile = pins["YTDLP_PROFILE"]
    spec = importlib.util.spec_from_file_location("extractor_profiles", ROOT / "Scripts/select-extractor-profile.py")
    profiles = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(profiles)
    if profiles.distribution_version(profile, pins["YTDLP_VERSION"]) != pins["YTDLP_PACKAGE_VERSION"]:
        raise ValueError("Extractor profile does not match the package pin")
    swift += f'    static let extractorProfile = "{profile}"\n'
    swift += "".join(f'    static let {name} = "{pins[pin]}"\n'
                     for name, pin in names.items()) + "}\n"
    python = "# Generated by Scripts/sync-dependency-versions.py.\n"
    python += "".join(f'{pin} = "{pins[pin]}"\n' for pin in names.values())
    outputs = {"Core/Models/DependencyVersions.swift": swift,
               "PythonApp/illucet_dependency_versions.py": python}
    stale = []
    for name, content in outputs.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(name)
        else:
            path.write_text(content)
    if stale:
        parser.exit(1, "Stale dependency expectations; run "
                    "Scripts/sync-dependency-versions.py: " + ", ".join(stale) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
